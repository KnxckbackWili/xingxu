import { act, fireEvent, render as rtlRender, screen, waitFor, within } from '@testing-library/react'
import { beforeEach, expect, it, vi } from 'vitest'
import TemplateDocumentsTab from './TemplateDocumentsTab'
import { ConfigProvider } from 'antd'
import type { ReactNode } from 'react'
const render = (ui: ReactNode) => rtlRender(ui, { wrapper: ({ children }) => <ConfigProvider theme={{ token: { motion: false } }}>{children}</ConfigProvider> })
const { get, post, put, del } = vi.hoisted(() => ({ get: vi.fn(), post: vi.fn(), put: vi.fn(), del: vi.fn() }))
vi.mock('../../api/client', () => ({ api: { get, post, put, delete: del } }))
const row = (extra = {}) => ({ id: 'r1', stage_key: '6', code: '6.2', name: '生命周期表', template_no: '模板9', is_group: false, parent_id: null, required: true, scope: 'project', platform: null, timing_type: 'weekly', timing_event: null, timing_offset_hours: null, timing_weekday: 7, trigger_type: null, confidential_default: false, external_visible_default: false, external_never_visible: false, sort_order: 1, note: '', blank_file: null, ...extra })
beforeEach(() => { vi.clearAllMocks(); get.mockResolvedValue({ data: [row()] }); post.mockResolvedValue({ data: {} }); put.mockResolvedValue({ data: {} }); del.mockResolvedValue({ data: {} }) })
it('只读显示资料规则、范围和未上传状态', async () => {
  render(<TemplateDocumentsTab templateId="default" editMode={false} />)
  expect(await screen.findByText('生命周期表')).toBeVisible()
  expect(screen.getByText('每周日')).toBeVisible()
  expect(screen.getByText('尚未上传空白模板')).toBeVisible()
  expect(screen.queryByRole('button', { name: '新增资料要求' })).not.toBeInTheDocument()
})
it('加载失败可重试，迟到的旧模板响应不能覆盖新模板', async () => {
  get.mockRejectedValueOnce(new Error('offline'))
  const view = render(<TemplateDocumentsTab templateId="old" editMode />)
  expect(await screen.findByText('资料要求加载失败')).toBeVisible()
  let oldResolve!: (value: unknown) => void
  get.mockImplementationOnce(() => new Promise(resolve => { oldResolve = resolve }))
  fireEvent.click(screen.getByRole('button', { name: /重.*试/ }))
  get.mockResolvedValueOnce({ data: [row({ id: 'new', name: '新模板资料' })] })
  view.rerender(<TemplateDocumentsTab templateId="new" editMode />)
  expect(await screen.findByText('新模板资料')).toBeVisible()
  await act(async () => oldResolve({ data: [row({ name: '旧模板资料' })] }))
  expect(screen.queryByText('旧模板资料')).not.toBeInTheDocument()
})
it('编辑每周资料保存完整规则字段，保存失败保留输入', async () => {
  put.mockRejectedValueOnce({ response: { data: { detail: '保存测试失败' } } })
  render(<TemplateDocumentsTab templateId="default" editMode />)
  fireEvent.click(await screen.findByRole('button', { name: '编辑资料6.2' }))
  const dialog = await screen.findByRole('dialog')
  fireEvent.change(within(dialog).getByLabelText('资料名称'), { target: { value: '生命周期表修订' } })
  fireEvent.click(within(dialog).getByRole('button', { name: /保.*存/ }))
  expect(await screen.findByText('保存测试失败')).toBeVisible()
  expect(within(dialog).getByLabelText('资料名称')).toHaveValue('生命周期表修订')
  expect(put.mock.calls[0][1]).toMatchObject({ timing_type: 'weekly', timing_weekday: 7, timing_event: null, timing_offset_hours: null, parent_id: null })
})
it('保密开关清除并禁用默认对外可见；全周期的隐藏启动事件不会丢失', async () => {
  get.mockResolvedValue({ data: [row({ timing_type: 'lifetime', timing_event: 'internal_kickoff', timing_weekday: null, external_visible_default: true })] })
  render(<TemplateDocumentsTab templateId="default" editMode />)
  fireEvent.click(await screen.findByRole('button', { name: '编辑资料6.2' }))
  const dialog = await screen.findByRole('dialog')
  fireEvent.click(within(dialog).getByLabelText('默认保密'))
  expect(within(dialog).getByLabelText('默认对外可见')).toBeDisabled()
  fireEvent.click(within(dialog).getByRole('button', { name: /保.*存/ }))
  await waitFor(() => expect(put).toHaveBeenCalledTimes(1))
  expect(put.mock.calls[0][1]).toMatchObject({ confidential_default: true, external_visible_default: false, timing_type: 'lifetime', timing_event: 'internal_kickoff', timing_weekday: null })
})
it('每周规则缺少星期时不能保存，重复保存只发送一次请求', async () => {
  get.mockResolvedValue({ data: [row({ timing_weekday: null })] })
  const view = render(<TemplateDocumentsTab templateId="default" editMode />)
  fireEvent.click(await screen.findByRole('button', { name: '编辑资料6.2' }))
  let dialog = await screen.findByRole('dialog')
  fireEvent.click(within(dialog).getByRole('button', { name: /保.*存/ }))
  await waitFor(() => expect(screen.getByText('每周规则必须选择星期')).toBeVisible())
  expect(put).not.toHaveBeenCalled()
  view.unmount()
  get.mockResolvedValue({ data: [row()] })
  let finish!: (value: unknown) => void
  put.mockImplementation(() => new Promise(resolve => { finish = resolve }))
  render(<TemplateDocumentsTab templateId="default" editMode />)
  fireEvent.click(await screen.findByRole('button', { name: '编辑资料6.2' }))
  dialog = await screen.findByRole('dialog')
  const save = within(dialog).getByRole('button', { name: /保.*存/ })
  fireEvent.click(save); fireEvent.click(save)
  await waitFor(() => expect(put).toHaveBeenCalledTimes(1))
  await act(async () => finish({ data: {} }))
})

it('legacy sources stay read-only and classification explicitly chooses a current stage without rewriting the source', async () => {
  const source = { source_type: 'template_task', original_stage: '公司评审', original: { name: '旧启动资料' } }
  get.mockResolvedValue({ data: [row({ stage_key: 'legacy', code: 'legacy-old', name: '旧启动资料', source_metadata: source })] })
  render(<TemplateDocumentsTab templateId="default" editMode />)
  expect(await screen.findByText('历史来源（只读）')).toBeInTheDocument()
  expect(screen.getByText(/"original_stage": "公司评审"/)).toBeInTheDocument()
  fireEvent.click(screen.getByRole('button', { name: '分类历史资料legacy-old' }))
  const dialog = await screen.findByRole('dialog')
  fireEvent.click(within(dialog).getByRole('button', { name: /保.*存/ }))
  await waitFor(() => expect(put).not.toHaveBeenCalled())
  fireEvent.mouseDown(within(dialog).getByLabelText('阶段'))
  fireEvent.click(await screen.findByText('4 · 内部启动会'))
  fireEvent.change(within(dialog).getByLabelText('编号'), { target: { value: '4.1' } })
  fireEvent.click(within(dialog).getByRole('button', { name: /保.*存/ }))
  await waitFor(() => expect(put).toHaveBeenCalledTimes(1))
  expect(put.mock.calls[0][1]).toMatchObject({ stage_key: '4', code: '4.1', name: '旧启动资料' })
  expect(put.mock.calls[0][1]).not.toHaveProperty('source_metadata')
})
