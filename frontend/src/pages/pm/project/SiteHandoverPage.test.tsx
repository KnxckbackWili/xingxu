import { beforeEach, expect, it, vi } from 'vitest'
import { fireEvent, render, screen, waitFor } from '@testing-library/react'
import { projectApi } from '../../../api'
import SiteHandoverPage from './SiteHandoverPage'
vi.mock('../../../api', () => ({ projectApi: { update: vi.fn() } }))
vi.mock('../../../api/client', () => ({ errMsg: () => '保存失败' }))
vi.mock('../../../stores/auth', () => ({ useAuth: () => ({ user: { id: 'admin', role: 'admin' } }) }))
vi.mock('../../../components/HandoverSummary', () => ({ default: () => null }))
beforeEach(() => vi.resetAllMocks())
it('keeps the contact draft open after failure and permits a successful retry', async () => {
  vi.mocked(projectApi.update).mockRejectedValueOnce(new Error('offline')).mockResolvedValueOnce({} as any)
  const reload = vi.fn()
  render(<SiteHandoverPage project={{ id: 'p1', client_contacts: [], entry_plan: {} } as any} onReload={reload} />)
  fireEvent.click(screen.getByRole('button', { name: /添加联系人/ }))
  fireEvent.change(screen.getByLabelText('姓名'), { target: { value: '王工' } })
  fireEvent.change(screen.getByLabelText('电话'), { target: { value: '12345' } })
  fireEvent.click(screen.getByRole('button', { name: /^保\s*存$/ }))
  await waitFor(() => expect(projectApi.update).toHaveBeenCalledTimes(1))
  await waitFor(() => expect(screen.getByRole('button', { name: /^保\s*存$/ })).not.toHaveClass('ant-btn-loading'))
  expect(screen.getByLabelText('姓名')).toHaveValue('王工')
  expect(screen.getByLabelText('电话')).toHaveValue('12345')
  expect(reload).not.toHaveBeenCalled()
  fireEvent.click(screen.getByRole('button', { name: /^保\s*存$/ }))
  await waitFor(() => expect(reload).toHaveBeenCalledTimes(1))
  expect(projectApi.update).toHaveBeenCalledTimes(2)
})

it('reads entry information first and preserves a failed edit for retry while server retains legacy fields', async () => {
  vi.mocked(projectApi.update).mockRejectedValueOnce(new Error('offline')).mockResolvedValueOnce({} as any)
  const reload = vi.fn()
  render(<SiteHandoverPage project={{id:'p1',entry_plan:{access_requirements:'持证入场',legacy_extra:'保留'},client_contacts:[]} as any} onReload={reload} />)
  expect(screen.getByText('持证入场')).toBeInTheDocument()
  expect(screen.queryByRole('textbox')).toBeNull()
  expect(projectApi.update).not.toHaveBeenCalled()
  fireEvent.click(screen.getByRole('button',{name:'编辑入场信息'}))
  fireEvent.change(screen.getByLabelText('入厂所需手续'),{target:{value:'提前登记'}})
  fireEvent.click(screen.getByRole('button',{name:'保存入场信息'}))
  expect(await screen.findByRole('alert')).toHaveTextContent('保存失败')
  expect(screen.getByLabelText('入厂所需手续')).toHaveValue('提前登记')
  expect(reload).not.toHaveBeenCalled()
  fireEvent.click(screen.getByRole('button',{name:'保存入场信息'}))
  await waitFor(()=>expect(reload).toHaveBeenCalledTimes(1))
  expect(projectApi.update).toHaveBeenLastCalledWith('p1',expect.objectContaining({entry_plan:expect.objectContaining({access_requirements:'提前登记'})}))
})
